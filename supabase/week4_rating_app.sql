create extension if not exists pgcrypto;

create table if not exists public.generations (
  id uuid primary key default gen_random_uuid(),
  created_by uuid not null references auth.users(id) on delete cascade,
  scene text not null check (char_length(scene) between 10 and 300),
  style text not null check (style in ('dry', 'chaotic', 'wholesome')),
  prompt text not null,
  caption text not null check (char_length(caption) between 1 and 500),
  model text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.votes (
  id bigint generated by default as identity primary key,
  generation_id uuid not null references public.generations(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  value smallint not null check (value in (-1, 1)),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (generation_id, user_id)
);

create index if not exists votes_generation_id_idx on public.votes(generation_id);

do $$
declare table_record record;
begin
  for table_record in select tablename from pg_tables where schemaname = 'public'
  loop
    execute format('alter table public.%I enable row level security', table_record.tablename);
  end loop;
end;
$$;

do $$
declare policy_record record;
begin
  for policy_record in
    select policyname from pg_policies
    where schemaname = 'public' and tablename = 'favorite_things'
  loop
    execute format('drop policy %I on public.favorite_things', policy_record.policyname);
  end loop;
end;
$$;

create policy "Anyone can read favorite things"
on public.favorite_things for select to anon, authenticated using (true);

drop policy if exists "Anyone can read generations" on public.generations;
create policy "Anyone can read generations"
on public.generations for select to anon, authenticated using (true);

drop policy if exists "Users can create their own generations" on public.generations;
create policy "Users can create their own generations"
on public.generations for insert to authenticated
with check ((select auth.uid()) = created_by);

drop policy if exists "Users can read their own votes" on public.votes;
create policy "Users can read their own votes"
on public.votes for select to authenticated
using ((select auth.uid()) = user_id);

drop policy if exists "Users can create their own votes" on public.votes;
create policy "Users can create their own votes"
on public.votes for insert to authenticated
with check ((select auth.uid()) = user_id);

drop policy if exists "Users can update their own votes" on public.votes;
create policy "Users can update their own votes"
on public.votes for update to authenticated
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

drop policy if exists "Users can delete their own votes" on public.votes;
create policy "Users can delete their own votes"
on public.votes for delete to authenticated
using ((select auth.uid()) = user_id);

create or replace function public.get_generation_scores()
returns table (generation_id uuid, upvotes bigint, downvotes bigint, score bigint)
language sql stable security definer set search_path = ''
as $$
  select
    votes.generation_id,
    count(*) filter (where votes.value = 1) as upvotes,
    count(*) filter (where votes.value = -1) as downvotes,
    coalesce(sum(votes.value), 0)::bigint as score
  from public.votes
  group by votes.generation_id;
$$;

revoke all on function public.get_generation_scores() from public;
grant execute on function public.get_generation_scores() to anon, authenticated;
